    def test_double_metaphone(self):
        """Test abydos.phonetic.DoubleMetaphone."""
        # base case
        assert self.pa.encode('') == ','

        # single result
        assert self.pa.encode('aubrey') == 'APR,'

        # double result
        assert self.pa.encode('richard') == 'RXRT,RKRT'

