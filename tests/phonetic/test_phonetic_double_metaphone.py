        assert self.pa.encode('bob') == 'PP,'
        assert self.pa.encode('ray') == 'R,'
        assert self.pa.encode('Tux') == 'TKS,'
        assert self.pa.encode('bryan') == 'PRN,'
        assert self.pa.encode('bryce') == 'PRS,'
